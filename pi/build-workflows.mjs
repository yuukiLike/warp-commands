import { readFileSync, writeFileSync } from "node:fs";

const here = file => new URL(file, import.meta.url);
const source = readFileSync(here("warp.mjs"), "utf8").trimEnd();
const seed = JSON.stringify(JSON.parse(readFileSync(here("settings.template.json"), "utf8")));
const check = process.argv.includes("--check");
const workflows = {
  "pi-model-start.yaml": { call: `startModel(process.argv.slice(1), ${seed})`, args: '"{{model}}" "{{thinking}}"' },
  "pi-settings-edit.yaml": { call: "editSettings()" },
  "pi-settings-merge.yaml": { call: `writeSettings("merge", ${seed})` },
  "pi-settings-overwrite.yaml": { call: `writeSettings("overwrite", ${seed})` },
};

// A command field owns only its own line and indented or blank continuation lines.
const commandField = /^command:[^\n]*(?:\n(?=\n|[ \t])[^\n]*)*/m;
for (const [name, { call, args }] of Object.entries(workflows)) {
  const file = here(name);
  const current = readFileSync(file, "utf8");
  if (!commandField.test(current)) throw new Error(`${name} 缺少 command。`);
  // Keep stdin attached to the terminal for Pi and vi; only the script comes from the heredoc.
  const command = [
    `node --input-type=module -e "$(command cat <<'WARP_PI_NODE'`,
    source,
    `run(() => ${call});`,
    "WARP_PI_NODE",
    args ? `)" -- ${args}` : `)"`,
  ].join("\n").split("\n").map(line => line ? `  ${line}` : "").join("\n");
  const rendered = current
    .replace(/^---\n(?!# command generated)/, "---\n# command generated by node pi/build-workflows.mjs\n")
    .replace(commandField, () => `command: |-\n${command}`);
  if (rendered === current) continue;
  if (check) {
    console.error(`${name} 未同步；运行 node pi/build-workflows.mjs。`);
    process.exitCode = 1;
  } else {
    writeFileSync(file, rendered);
  }
}
